# 3)შექმენი სია სადაც მოათავსებთ ინტეჯერ ტიპის მოანცემებს,შენი დავალებაა დაითვალო თუ რამდენი ცალი რიცხვი გვხვდება სიაში რომელიც არის 50 ზე მეტი


int_list=[10, 55, 68, 23, 89, 45, 150, 32, 78, 49]
count=0
for number in range(len(int_list)):
    if int_list[number]>50:
        count=count+1
print("50 ზე მეტი რიცხვების რაოდენობა არის:",count)