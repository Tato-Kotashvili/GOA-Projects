# 7) შექმენი ფუქნცია რომელიც მომხმარებელს შემოაყვანინებს რაღაც რიცხვს და დააბრუნებს სიტყვას ეს რიცხვი დადებითია უარყოფითია თუ ნულია

def negative_or_positive():
    num=int(input("შეიყვანეთ რიცხვი: "))
    if num>0:
        print("ეს რიცხვი დადებითია")
    elif num<0:
        print("ეს რიცხვი უარყოფითია")
    else:
        print("ეს რიცხვი ნულია")
negative_or_positive()
