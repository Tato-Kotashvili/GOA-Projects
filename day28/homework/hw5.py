# 5) მომხმარებელს შეაყვანინე რიცხვები, მანამ სანამ არ შეიყვანს 0, ყოველი რიცხვის შემდეგ დაბეჭდე "დადებითია" ან "უარყოფითია".დაბეჭდე ბოლოს რიცხვების ჯამი. გამოიყენე while loop.


total = 0
number = int(input("შეიყვანეთ რიცხვი (0 გამოსასვლელად): "))
while number != 0:
    if number > 0:
        print("დადებითია")
    else:
        print("უარყოფითია")
    total = total + number
    number = int(input("შეიყვანეთ რიცხვი (0 გამოსასვლელად): "))
print("რიცხვების ჯამი არის:", total)