# შენი დავალებაა რომ ტერმინალში გამოიტანო სიის თითუეული ელემენტი ცალ ცალკე ,გამოიყენე for და while ციკლები 


names = ["Nika", "Giorgi", "Ana", "Luka", "Mari"]
# for loop
for i in range(len(names)):
    print(names[i])
    
# while loop
index = 0
while index < len(names):
    print(names[index])
    index = index + 1