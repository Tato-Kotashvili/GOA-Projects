# მოახდინე სლაისინგი --> start იყოს პირველი რიცხვი და end იყოს მეორე შემოტანილი რიცხვი

string = "ჰიდროელექტროსადგური"
start = int(input("შეიყვანეთ პირველი რიცხვი (0-19): "))
end = int(input("შეიყვანეთ მეორე რიცხვი (0-19): "))
sliced_string = string[start:end]
print(sliced_string)